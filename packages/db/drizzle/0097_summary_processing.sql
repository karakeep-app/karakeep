CREATE TABLE `summaryProcessing` (
	`bookmarkId` text PRIMARY KEY NOT NULL,
	`userId` text NOT NULL,
	`generation` text NOT NULL,
	`sourceUrl` text NOT NULL,
	`sourceVersion` text NOT NULL,
	`sourceType` text NOT NULL,
	`status` text NOT NULL,
	`provider` text,
	`publishedGeneration` text,
	`publishedSourceVersion` text,
	`summaryHash` text,
	`generatedAt` integer,
	`transcriptAssetId` text,
	`notebookId` text,
	`errorCode` text,
	`updatedAt` integer NOT NULL,
	FOREIGN KEY (`bookmarkId`) REFERENCES `bookmarks`(`id`) ON UPDATE no action ON DELETE cascade,
	FOREIGN KEY (`userId`) REFERENCES `user`(`id`) ON UPDATE no action ON DELETE cascade,
	FOREIGN KEY (`transcriptAssetId`) REFERENCES `assets`(`id`) ON UPDATE no action ON DELETE set null
);
